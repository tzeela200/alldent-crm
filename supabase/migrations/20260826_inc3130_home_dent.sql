-- ───────────────────────────────────────────────────────────────────────────
-- 18. פרסום · עדכון · הסרה · הארכה
-- ───────────────────────────────────────────────────────────────────────────
create or replace function public.publish_dental_asset(p_asset_id uuid)
returns jsonb language plpgsql security definer
set search_path = '' as $fn$
declare a public.dental_assets%rowtype; v jsonb; v_ends timestamptz; v_ver int;
begin
  if (select auth.uid()) is null then raise exception 'not_authenticated' using errcode='42501'; end if;
  select * into a from public.dental_assets where id = p_asset_id for update;
  if not found then raise exception 'asset_was_not_found'; end if;
  if a.package_days is null then raise exception 'package_days_invalid'; end if;

  perform public.hd_publish_gate(p_asset_id);
  v := public.hd_build_publication_payload(p_asset_id);

  -- השעון מתחיל בפרסום הראשון בפועל, ולא מתאפס בעדכונים (§61)
  v_ends := coalesce(a.ends_at, now() + make_interval(days => a.package_days));

  update public.dental_asset_publications
     set status = 'superseded', superseded_at = now()
   where asset_id = p_asset_id and status = 'live';

  select coalesce(max(version_number),0)+1 into v_ver
    from public.dental_asset_publications where asset_id = p_asset_id;

  insert into public.dental_asset_publications
    (asset_id, asset_code, version_number, status, public_page, public_card,
     published_at, expires_at, published_by)
  values (p_asset_id, a.asset_code, v_ver, 'live', v -> 'page', v -> 'card',
          now(), v_ends, (select auth.uid()));

  update public.dental_assets
     set publication_state  = 'published',
         first_published_at = coalesce(first_published_at, now()),
         ends_at            = v_ends,
         last_published_at  = now(),
         current_version    = v_ver,
         workflow_status    = case when workflow_status = 'archived' then workflow_status else 'ready' end
   where id = p_asset_id;

  return jsonb_build_object('status','published','version',v_ver,'ends_at',v_ends);
end $fn$;

-- Publish Update — אותה פונקציה. גרסה חדשה, אותו שעון.
create or replace function public.publish_dental_asset_update(p_asset_id uuid)
returns jsonb language plpgsql security definer
set search_path = '' as $fn$
begin
  if (select auth.uid()) is null then raise exception 'not_authenticated' using errcode='42501'; end if;
  if not exists (select 1 from public.dental_asset_publications
                  where asset_id = p_asset_id and status = 'live') then
    raise exception 'no_live_publication';
  end if;
  return public.publish_dental_asset(p_asset_id);
end $fn$;

create or replace function public.unpublish_dental_asset(p_asset_id uuid, p_reason text default null)
returns jsonb language plpgsql security definer
set search_path = '' as $fn$
begin
  if (select auth.uid()) is null then raise exception 'not_authenticated' using errcode='42501'; end if;
  update public.dental_asset_publications
     set status = 'removed', superseded_at = now()
   where asset_id = p_asset_id and status = 'live';
  update public.dental_assets set publication_state = 'removed' where id = p_asset_id;
  return jsonb_build_object('status','removed');
end $fn$;

-- הארכה ידנית (החלטה 10). אין תשלום, אין הזמנה חדשה, אין אוטומציה.
create or replace function public.extend_dental_asset(
  p_asset_id uuid, p_new_ends_at timestamptz, p_reason text default null)
returns jsonb language plpgsql security definer
set search_path = '' as $fn$
declare v_old timestamptz;
begin
  if (select auth.uid()) is null then raise exception 'not_authenticated' using errcode='42501'; end if;
  if p_new_ends_at is null then raise exception 'new_end_date_missing'; end if;

  select ends_at into v_old from public.dental_assets where id = p_asset_id for update;

  update public.dental_assets
     set ends_at = p_new_ends_at,
         period_history = period_history || jsonb_build_object(
           'old', v_old, 'new', p_new_ends_at, 'reason', p_reason,
           'by', (select auth.uid()), 'at', now())
   where id = p_asset_id;

  update public.dental_asset_publications
     set expires_at = p_new_ends_at
   where asset_id = p_asset_id and status = 'live';

  return jsonb_build_object('status','extended','ends_at',p_new_ends_at);
end $fn$;

