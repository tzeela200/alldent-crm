  p_imaging_notes text, p_equipment_notes text, p_services_notes text,
  p_offers jsonb, p_images jsonb,
  p_package_days smallint, p_screening boolean, p_terms_version text,
  p_terms_accepted boolean, p_source_page text, p_source_url text
) returns table (status text, asset_code text, asset_id uuid)
language plpgsql security definer
set search_path = '' as $$
declare
  v_id uuid; v_code text; v_phone text; v_o jsonb; v_i jsonb; v_n int;
begin
  if coalesce(p_terms_accepted, false) is not true then
    raise exception 'terms_were_not_accepted';
  end if;
  if nullif(btrim(coalesce(p_client_name, '')), '') is null then
    raise exception 'client_name_is_missing';
  end if;

  v_phone := public.normalize_il_mobile_phone(p_client_phone);
  if v_phone is null then
    raise exception 'client_phone_is_invalid';
  end if;

  if p_package_days is null or p_package_days not in (60, 90) then
    raise exception 'package_days_invalid';
  end if;
  if p_city_id is null or not exists (select 1 from public.dict_cities d where d.id = p_city_id) then
    raise exception 'city_was_not_found';
  end if;
  if p_asset_type is null then
    raise exception 'asset_type_missing';
  end if;

  -- מניעת הגשה כפולה בטעות (רענון / לחיצה כפולה)
  if exists (select 1 from public.dental_assets a
              where a.client_phone_norm = v_phone
                and a.city_id = p_city_id
                and a.created_at > now() - interval '12 hours') then
    raise exception 'duplicate_recent_request';
  end if;

  -- כל מזהה מילון חייב להיות קיים ופעיל. עם טבלה אחת זו בדיקה אחת
  -- במקום שש; עם שש טבלאות ויתרתי עליה לגמרי.
  if exists (
    select 1 from unnest(
      coalesce(p_accessibility_ids,'{}') || coalesce(p_premises_feature_ids,'{}') ||
      coalesce(p_imaging_equipment_ids,'{}') || coalesce(p_equipment_ids,'{}') ||
      coalesce(p_service_ids,'{}')) u(oid)
    where not exists (select 1 from public.dict_dental_options d
                       where d.id = u.oid and d.is_active)
  ) then
    raise exception 'unknown_dictionary_id';
  end if;

  if p_offers is null or jsonb_array_length(p_offers) = 0 then
    raise exception 'offers_list_is_empty';
  end if;

  v_n := coalesce(jsonb_array_length(p_images), 0);
  if v_n > 15 then
    raise exception 'too_many_images';   -- החלטה 9: 15 להגשת הלקוח בלבד
  end if;

  -- כל נתיב תמונה חייב לשבת תחת ה-token שנשלח, אחרת אפשר לצרף קובץ זר
  if p_images is not null then
    for v_i in select * from jsonb_array_elements(p_images) loop
      if (v_i ->> 'private_path') is null
         or position((p_submission_token::text || '/') in (v_i ->> 'private_path')) <> 1 then
        raise exception 'image_path_outside_token';
      end if;
    end loop;
  end if;

  insert into public.dental_assets (
    source, submission_token, source_page, source_url,
    workflow_status, publication_state,
    package_days, package_price_shown, screening_selected,
    terms_version, terms_accepted_at,                      -- ← now(), לא מהלקוח
    clinic_name, city_id, street, street_number, entrance, floor,
    area_sqm, rooms_count, units_count, years_active,
    asset_type, clinic_type, location_type, client_notes,
    accessibility_ids, premises_feature_ids, imaging_equipment_ids,
    equipment_ids, service_ids, imaging_notes, equipment_notes, services_notes,
    client_name, client_business_name, client_phone, client_phone_norm,
    client_whatsapp, client_email, client_contact_notes,
    internal_title, submission_snapshot
  ) values (
    'public_form', p_submission_token,
    nullif(btrim(coalesce(p_source_page,'')),''), nullif(btrim(coalesce(p_source_url,'')),''),
    'new', 'draft',
    p_package_days, case p_package_days when 60 then 700 else 800 end, coalesce(p_screening,false),
    p_terms_version, now(),
    nullif(btrim(coalesce(p_clinic_name,'')),''), p_city_id,
    nullif(btrim(coalesce(p_street,'')),''), nullif(btrim(coalesce(p_street_number,'')),''),
    nullif(btrim(coalesce(p_entrance,'')),''), nullif(btrim(coalesce(p_floor,'')),''),
    p_area_sqm, p_rooms_count, p_units_count, p_years_active,
    p_asset_type, p_clinic_type, p_location_type, nullif(btrim(coalesce(p_client_notes,'')),''),
    coalesce(p_accessibility_ids,'{}'), coalesce(p_premises_feature_ids,'{}'),
    coalesce(p_imaging_equipment_ids,'{}'), coalesce(p_equipment_ids,'{}'),
    coalesce(p_service_ids,'{}'),
    nullif(btrim(coalesce(p_imaging_notes,'')),''), nullif(btrim(coalesce(p_equipment_notes,'')),''),
    nullif(btrim(coalesce(p_services_notes,'')),''),
    btrim(p_client_name), nullif(btrim(coalesce(p_client_business_name,'')),''),
    btrim(p_client_phone), v_phone,
    nullif(btrim(coalesce(p_client_whatsapp,'')),''), lower(nullif(btrim(coalesce(p_client_email,'')),'')),
    nullif(btrim(coalesce(p_client_contact_notes,'')),''),
    coalesce(nullif(btrim(coalesce(p_clinic_name,'')),''), 'נכס חדש'),
    jsonb_build_object(
      'received_at', now(),
      'client', jsonb_build_object('name',p_client_name,'business',p_client_business_name,
                 'phone',p_client_phone,'whatsapp',p_client_whatsapp,'email',p_client_email,
                 'notes',p_client_contact_notes),
      'asset', jsonb_build_object('clinic_name',p_clinic_name,'city_id',p_city_id,'street',p_street,
                 'street_number',p_street_number,'entrance',p_entrance,'floor',p_floor,
                 'area_sqm',p_area_sqm,'rooms_count',p_rooms_count,'units_count',p_units_count,
                 'years_active',p_years_active,'asset_type',p_asset_type,'clinic_type',p_clinic_type,
                 'location_type',p_location_type,'notes',p_client_notes),
      'dicts', jsonb_build_object('accessibility',p_accessibility_ids,'premises',p_premises_feature_ids,
                 'imaging',p_imaging_equipment_ids,'equipment',p_equipment_ids,'services',p_service_ids,
                 'imaging_notes',p_imaging_notes,'equipment_notes',p_equipment_notes,
                 'services_notes',p_services_notes),
      'offers', p_offers,
      'images', p_images,
      'service', jsonb_build_object('package_days',p_package_days,'screening',p_screening,
                 'terms_version',p_terms_version)
    )
  ) returning id, asset_code into v_id, v_code;

  -- מסלולי עסקה
  for v_o in select * from jsonb_array_elements(p_offers) loop
    if (v_o ->> 'offer_type') not in ('sale','rent_monthly','rent_daily','rent_shift') then
      raise exception 'offer_type_is_invalid';
    end if;
    insert into public.dental_asset_offers (
      asset_id, offer_type, price_amount, price_unit, available_from,
      availability_note, days, hours, included_note, extra_costs_note,
      terms_note, sale_include_ids, notes, sort_order
    ) values (
      v_id, v_o ->> 'offer_type',
      nullif(v_o ->> 'price_amount','')::numeric,
      case when nullif(v_o ->> 'price_amount','') is null then null
           else case v_o ->> 'offer_type'
                  when 'sale' then 'total' when 'rent_monthly' then 'per_month'
                  when 'rent_daily' then 'per_day' else 'per_shift' end end,
      nullif(v_o ->> 'available_from','')::date,
      nullif(btrim(coalesce(v_o ->> 'availability_note','')),''),
      coalesce((select array_agg(x::smallint) from jsonb_array_elements_text(
                  coalesce(v_o -> 'days','[]'::jsonb)) t(x)), '{}'),
      nullif(btrim(coalesce(v_o ->> 'hours','')),''),
      nullif(btrim(coalesce(v_o ->> 'included_note','')),''),
      nullif(btrim(coalesce(v_o ->> 'extra_costs_note','')),''),
      nullif(btrim(coalesce(v_o ->> 'terms_note','')),''),
      coalesce((select array_agg(x::bigint) from jsonb_array_elements_text(
                  coalesce(v_o -> 'sale_include_ids','[]'::jsonb)) t(x)), '{}'),
      nullif(btrim(coalesce(v_o ->> 'notes','')),''),
      coalesce(nullif(v_o ->> 'sort_order','')::smallint, 1)
    );
  end loop;

  -- תמונות — נכנסות פרטיות ולא מסומנות לפרסום (§30)
  if p_images is not null then
    v_n := 0;
    for v_i in select * from jsonb_array_elements(p_images) loop
      v_n := v_n + 1;
      insert into public.dental_asset_images (
        asset_id, private_path, original_filename, mime_type, byte_size, sort_order, is_published
      ) values (
        v_id, v_i ->> 'private_path',
        nullif(v_i ->> 'original_filename',''), nullif(v_i ->> 'mime_type',''),
        nullif(v_i ->> 'byte_size','')::int, v_n::smallint, false
      );
    end loop;
  end if;

  return query select 'success'::text, v_code, v_id;
end $$;

-- ───────────────────────────────────────────────────────────────────────────
-- 11. RPC ציבורי — השארת פרטים (§68)
--     מאתר את הנכס דרך הפרסום החי בלבד. אחרת אפשר לפנות לנכס שלא פורסם
--     ולגלות קודי HD תקפים לפי הבדל בשגיאה.
-- ───────────────────────────────────────────────────────────────────────────
create or replace function public.submit_dental_asset_inquiry(
  p_asset_code text, p_offer_id uuid, p_name text, p_phone text,
  p_email text, p_message text, p_source_url text, p_consent boolean
) returns table (status text, inquiry_id uuid)
language plpgsql security definer
set search_path = '' as $$
declare
  v_asset uuid; v_pub uuid; v_code text; v_phone text; v_label text; v_id uuid;
begin
  if coalesce(p_consent, false) is not true then
    raise exception 'consent_was_not_given';
  end if;
  if nullif(btrim(coalesce(p_name,'')), '') is null then
    raise exception 'lead_name_is_missing';
  end if;

  v_phone := public.normalize_il_mobile_phone(p_phone);
  if v_phone is null then
    raise exception 'lead_phone_is_invalid';
  end if;

  select p.asset_id, p.id, p.asset_code into v_asset, v_pub, v_code
  from public.dental_asset_publications p
  where p.asset_code = upper(btrim(p_asset_code))
    and p.status = 'live'
    and p.published_at <= now()
    and (p.expires_at is null or p.expires_at > now());
  if not found then
    raise exception 'asset_is_not_published';
  end if;

  if p_offer_id is not null then
    select case o.offer_type
             when 'sale' then 'מכירה' when 'rent_monthly' then 'שכירות חודשית'
             when 'rent_daily' then 'השכרה יומית' else 'השכרה לפי משמרת' end
      into v_label
    from public.dental_asset_offers o where o.id = p_offer_id and o.asset_id = v_asset;
    if v_label is null then
      raise exception 'offer_not_on_this_asset';
    end if;
  end if;

  if exists (select 1 from public.dental_asset_inquiries i
              where i.asset_id = v_asset and i.phone_norm = v_phone
                and i.created_at > now() - interval '12 hours') then
    raise exception 'duplicate_recent_lead';
  end if;

  insert into public.dental_asset_inquiries
    (asset_id, asset_code, offer_id, offer_label, publication_id,
     name, phone, phone_norm, email, message, source_url, consent)
  values
    (v_asset, v_code, p_offer_id, v_label, v_pub,
     btrim(p_name), btrim(p_phone), v_phone,
     lower(nullif(btrim(coalesce(p_email,'')),'')),
     nullif(btrim(coalesce(p_message,'')),''),
     nullif(btrim(coalesce(p_source_url,'')),''), true)
  returning id into v_id;

  return query select 'success'::text, v_id;
end $$;


