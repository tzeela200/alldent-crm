-- הקפאת מקור הלקוח (§41). לא ניתן לאכוף ב-CHECK כי נדרש OLD.
create or replace function public.hd_freeze_submission()
returns trigger language plpgsql
set search_path = '' as $$
begin
  if old.submission_snapshot is not null
     and new.submission_snapshot is distinct from old.submission_snapshot then
    raise exception 'submission_snapshot_is_immutable' using errcode = '42501';
  end if;
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists hd_assets_freeze on public.dental_assets;
create trigger hd_assets_freeze before update on public.dental_assets
  for each row execute function public.hd_freeze_submission();

