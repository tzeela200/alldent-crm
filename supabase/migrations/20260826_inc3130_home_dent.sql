create table if not exists public.dental_asset_offers (
  id                uuid primary key default gen_random_uuid(),
  asset_id          uuid not null references public.dental_assets(id) on delete cascade,
  offer_type        text not null,
  price_amount      numeric(12,2) check (price_amount is null or price_amount > 0),
  price_unit        text,
  -- החלטה 4: מלל חופשי שהאדמין כותב. לא סטטוס, לא מנגנון חשיפה.
  price_note        text,
  available_from    date,
  availability_note text,
  days              smallint[] not null default '{}',
  hours             text,
  included_note     text,
  extra_costs_note  text,
  terms_note        text,
  sale_include_ids  bigint[] not null default '{}',
  notes             text,
  sort_order        smallint not null default 1,
  is_active         boolean not null default true,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),

  constraint hd_offer_type_ck check (offer_type in ('sale','rent_monthly','rent_daily','rent_shift')),
  constraint hd_offer_unit_ck check (price_unit is null or price_unit in ('total','per_month','per_day','per_shift')),
  -- מחיר בלי יחידת מחיר אינו תקין
  constraint hd_offer_pair_ck check (price_amount is null or price_unit is not null),
  -- והיחידה חייבת להתאים לסוג העסקה
  constraint hd_offer_match_ck check (price_unit is null or price_unit = case offer_type
        when 'sale' then 'total' when 'rent_monthly' then 'per_month'
        when 'rent_daily' then 'per_day' else 'per_shift' end),
  constraint hd_offer_days_ck  check (days <@ array[0,1,2,3,4,5,6]::smallint[])
);
create index if not exists hd_offers_asset_idx on public.dental_asset_offers (asset_id, sort_order);
