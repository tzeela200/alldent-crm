create or replace function public.submit_public_dental_asset(
  p_submission_token uuid,
  p_client_name text, p_client_business_name text, p_client_phone text,
  p_client_whatsapp text, p_client_email text, p_client_contact_notes text,
  p_clinic_name text, p_city_id bigint, p_street text, p_street_number text,
  p_entrance text, p_floor text, p_area_sqm numeric, p_rooms_count smallint,
