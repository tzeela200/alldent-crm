-- 15. בניית התוכן הציבורי — הפונקציה המרכזית.
--     בונה payload מהנתונים המאושרים בלבד. שדה נכנס רק אם המפתח שלו
--     ב-published_fields; תמונה רק אם is_published; מסלול רק אם is_active.
--     פרטי הלקוח (client_*) לא נכנסים בשום תנאי — הם לא ברשימת המפתחות
--     ואין להם ענף בקוד. פרטי הקשר הציבוריים נלקחים מ-public_contact בלבד.
-- ───────────────────────────────────────────────────────────────────────────
create or replace function public.hd_build_publication_payload(p_asset_id uuid)
returns jsonb language plpgsql stable security definer
set search_path = '' as $fn$
declare
  a           public.dental_assets%rowtype;
  v_city      text;
  v_region    text;
  v_has       boolean;
  v_facts     jsonb := '[]'::jsonb;
  v_offers    jsonb := '[]'::jsonb;
  v_images    jsonb := '[]'::jsonb;
  v_groups    jsonb := '{}'::jsonb;
  v_cover     jsonb;
  v_card      jsonb;
  v_page      jsonb;
  r           record;
begin
  select * into a from public.dental_assets where id = p_asset_id;
  if not found then raise exception 'asset_was_not_found'; end if;

  select c.name into v_city   from public.dict_cities  c where c.id = a.city_id;
  select g.name into v_region from public.dict_regions g where g.id = a.region_id;

  -- נתוני מפתח — רק מפתחות שסומנו
  v_has := 'area_sqm' = any(a.published_fields);
  if v_has and a.area_sqm is not null then
    v_facts := v_facts || jsonb_build_object('key','area_sqm','label','שטח','value',a.area_sqm,'unit','מ״ר');
  end if;
  if 'rooms_count' = any(a.published_fields) and a.rooms_count is not null then
    v_facts := v_facts || jsonb_build_object('key','rooms_count','label','חדרי טיפול','value',a.rooms_count);
  end if;
  if 'units_count' = any(a.published_fields) and a.units_count is not null then
    v_facts := v_facts || jsonb_build_object('key','units_count','label','יוניטים','value',a.units_count);
  end if;
  if 'years_active' = any(a.published_fields) and a.years_active is not null then
    v_facts := v_facts || jsonb_build_object('key','years_active','label','ותק','value',a.years_active,'unit','שנים');
  end if;

  -- קבוצות ציוד — שמות מהמילון, לא מזהים
  for r in
    select k.key, k.label, k.ids from (values
        ('accessibility','נגישות וסביבה', a.accessibility_ids),
        ('premises','מה קיים בנכס',       a.premises_feature_ids),
        ('imaging','ציוד דימות',          a.imaging_equipment_ids),
        ('equipment','ציוד ומכשור',       a.equipment_ids),
        ('services','שירותים ותשתיות',    a.service_ids)
      ) as k(key,label,ids)
  loop
    if r.key = any(a.published_fields) and coalesce(array_length(r.ids,1),0) > 0 then
      v_groups := v_groups || jsonb_build_object(r.key, jsonb_build_object(
        'label', r.label,
        'items', coalesce((select jsonb_agg(d.name order by d.sort_order)
                             from public.dict_dental_options d where d.id = any(r.ids)), '[]'::jsonb)));
    end if;
  end loop;
  if 'imaging' = any(a.published_fields) and a.imaging_notes is not null then
    v_groups := jsonb_set(v_groups, '{imaging,note}', to_jsonb(a.imaging_notes), true);
  end if;
  if 'equipment' = any(a.published_fields) and a.equipment_notes is not null then
    v_groups := jsonb_set(v_groups, '{equipment,note}', to_jsonb(a.equipment_notes), true);
  end if;
  if 'services' = any(a.published_fields) and a.services_notes is not null then
    v_groups := jsonb_set(v_groups, '{services,note}', to_jsonb(a.services_notes), true);
  end if;

  -- מסלולי עסקה פעילים בלבד
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', o.id, 'offer_type', o.offer_type,
           'price_amount', case when 'price' = any(a.published_fields) then o.price_amount end,
           'price_unit',   case when 'price' = any(a.published_fields) then o.price_unit end,
           'price_note',   o.price_note,
           'available_from',    case when 'availability' = any(a.published_fields) then o.available_from end,
           'availability_note', case when 'availability' = any(a.published_fields) then o.availability_note end,
           'days',  case when 'days'  = any(a.published_fields) then to_jsonb(o.days) end,
           'hours', case when 'hours' = any(a.published_fields) then o.hours end,
           'included_note',    case when 'included'    = any(a.published_fields) then o.included_note end,
           'extra_costs_note', case when 'extra_costs' = any(a.published_fields) then o.extra_costs_note end,
           'terms_note',       case when 'terms'       = any(a.published_fields) then o.terms_note end,
           'sale_includes', case when 'included' = any(a.published_fields) then
              coalesce((select jsonb_agg(d.name order by d.sort_order)
                          from public.dict_dental_options d where d.id = any(o.sale_include_ids)), '[]'::jsonb) end
         ) order by o.sort_order), '[]'::jsonb)
    into v_offers
  from public.dental_asset_offers o
  where o.asset_id = p_asset_id and o.is_active;

  -- תמונות שסומנו לפרסום בלבד
  select coalesce(jsonb_agg(jsonb_build_object(
           'path', i.public_path, 'alt', i.alt_text, 'caption', i.caption,
           'focal_x', i.focal_x, 'focal_y', i.focal_y) order by i.sort_order), '[]'::jsonb)
    into v_images
  from public.dental_asset_images i
  where i.asset_id = p_asset_id and i.is_published and i.public_path is not null;

  v_cover := coalesce(v_images -> 0, 'null'::jsonb);

  v_card := jsonb_strip_nulls(jsonb_build_object(
    'asset_code',   a.asset_code,
    'title',        a.card_config ->> 'title',
    'location',     coalesce(a.card_config ->> 'location', v_city),
    'type_label',   a.card_config ->> 'type_label',
    'excerpt',      a.card_config ->> 'excerpt',
    'highlights',   a.card_config -> 'highlights',
    'tags',         a.card_config -> 'tags',
    'image',        coalesce(a.card_config -> 'image', v_cover),
    'offer_types',  (select coalesce(jsonb_agg(distinct o.offer_type), '[]'::jsonb)
                       from public.dental_asset_offers o
                      where o.asset_id = p_asset_id and o.is_active)));

  v_page := jsonb_strip_nulls(jsonb_build_object(
    'asset_code',  a.asset_code,
    'template',    'fixed_v1',
    'title',       a.card_config ->> 'public_title',
    'subtitle',    a.card_config ->> 'public_subtitle',
    'description', a.card_config ->> 'public_description',
    'clinic_name', case when 'clinic_name' = any(a.published_fields) then a.clinic_name end,
    'asset_type',  case when 'asset_type'  = any(a.published_fields) then a.asset_type end,
    'clinic_type', case when 'clinic_type' = any(a.published_fields) then a.clinic_type end,
    'location', jsonb_strip_nulls(jsonb_build_object(
       'city',   case when 'city'   = any(a.published_fields) then v_city end,
       'region', case when 'region' = any(a.published_fields) then v_region end,
       'street', case when 'street' = any(a.published_fields) then a.street end,
       'street_number', case when 'street_number' = any(a.published_fields) then a.street_number end,
       'floor',    case when 'floor'    = any(a.published_fields) then a.floor end,
       'entrance', case when 'entrance' = any(a.published_fields) then a.entrance end,
       'label',    a.card_config ->> 'location')),
    'facts',   v_facts,
    'groups',  v_groups,
    'offers',  v_offers,
    'images',  v_images,
    'contact', a.public_contact,     -- מה שהוזן באדמין. לא נשאב מ-client_*
    'ctas',    a.cta_buttons,
    'seo', jsonb_strip_nulls(jsonb_build_object(
       'og_title',       coalesce(a.card_config ->> 'og_title',       a.card_config ->> 'title'),
       'og_description', coalesce(a.card_config ->> 'og_description', a.card_config ->> 'excerpt'),
       'og_image',       coalesce(a.card_config ->> 'og_image',       v_cover ->> 'path')))));

  -- רשת ביטחון: אם מפתח פרטי הצליח להיכנס, הפרסום נכשל ולא יוצא לאוויר
  if v_page::text ~ '(client_phone|client_email|client_name|client_whatsapp|admin_notes|private_path|submission_snapshot|internal_title)' then
    raise exception 'payload_contains_private_key' using errcode = '42501';
  end if;

  return jsonb_build_object('page', v_page, 'card', v_card);
end $fn$;

-- ───────────────────────────────────────────────────────────────────────────
-- 16. שער הפרסום — חוסם רק מה שישבור את התצוגה (החלטה 8).
--     אין מחיר, אין טלפון, אין Waze, אין ציוד — לא חוסם.
-- ───────────────────────────────────────────────────────────────────────────
create or replace function public.hd_publish_gate(p_asset_id uuid)
returns void language plpgsql stable
set search_path = '' as $fn$
declare a public.dental_assets%rowtype;
begin
  select * into a from public.dental_assets where id = p_asset_id;
  if not found then raise exception 'asset_was_not_found'; end if;

  if nullif(btrim(coalesce(a.card_config ->> 'title','')), '') is null then
    raise exception 'public_title_is_empty';
  end if;
  if not exists (select 1 from public.dental_asset_images i
                  where i.asset_id = p_asset_id and i.is_published and i.public_path is not null) then
    raise exception 'no_published_image';
  end if;
  if exists (select 1 from public.dental_asset_images i
              where i.asset_id = p_asset_id and i.is_published and i.public_path is null) then
    raise exception 'image_copy_is_pending';
  end if;
  if coalesce(array_length(a.published_fields,1),0) = 0
     and not exists (select 1 from public.dental_asset_offers o
                      where o.asset_id = p_asset_id and o.is_active) then
    raise exception 'nothing_selected_for_publishing';
  end if;
end $fn$;

